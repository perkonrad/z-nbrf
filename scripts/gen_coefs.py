#!/usr/bin/env python3
"""Generate filter coefficients, preamble and CORDIC table for nb_radio.

Rate plan (fabric clock = 320 MHz, 1 complex sample/clk from RFDC):
    fs0 = 320 MSPS  (RFDC DDC IQ, x8 decimation of 2.56 GSPS; DUC x8 to 5.12 GSPS)
    fs1 = fs0/R     (CIC, R = 8..63)          = 8 samples/symbol
    fs2 = fs1/2     (CFIR half-rate)          = 4 samples/symbol (RRC, AGC, timing)
    Rs  = fs0/(8R)  = 40/R MBd, occupied BW = Rs*(1+alpha) = 50/R MHz  -> 1..5 MHz (R = 50..10)
All coefficients are in units of the symbol rate, so they don't depend on fs0.
"""
import numpy as np
from scipy import signal
import os, sys

OUT = os.path.join(os.path.dirname(__file__), "..", "rtl", "nb_coefs_pkg.sv")
ALPHA = 0.25
CIC_N = 4
CW = 18


def rrc(sps, span, alpha):
    n = np.arange(-span * sps // 2, span * sps // 2 + 1) / sps
    h = np.zeros_like(n)
    for i, t in enumerate(n):
        if abs(t) < 1e-12:
            h[i] = 1 - alpha + 4 * alpha / np.pi
        elif abs(abs(t) - 1 / (4 * alpha)) < 1e-9:
            h[i] = alpha / np.sqrt(2) * ((1 + 2 / np.pi) * np.sin(np.pi / (4 * alpha))
                                         + (1 - 2 / np.pi) * np.cos(np.pi / (4 * alpha)))
        else:
            h[i] = (np.sin(np.pi * t * (1 - alpha)) + 4 * alpha * t * np.cos(np.pi * t * (1 + alpha))) / \
                   (np.pi * t * (1 - (4 * alpha * t) ** 2))
    return h


def quant(h, frac):
    q = np.round(h * 2 ** frac).astype(int)
    assert q.max() < 2 ** (CW - 1) and q.min() >= -2 ** (CW - 1), "coef overflow"
    return q


def packvec(q):
    # element k at bits [k*CW +: CW]
    v = 0
    for k, c in enumerate(q):
        v |= (int(c) & ((1 << CW) - 1)) << (k * CW)
    return f"{len(q) * CW}'h{v:0{(len(q) * CW + 3) // 4}x}"


# ---------------- CFIR: CIC droop compensation + x2 rate change at fs1 -------------
# Frequencies in units of fs1. Passband edge 0.625*Rs = 0.078 fs1.
NCF = 23
fp, fs_ = 0.10, 0.40
f = np.linspace(0, 0.5, 2048)
grid_p = f[f <= fp]
cic_resp = lambda x: np.abs(np.sinc(x)) ** CIC_N    # large-R approximation in fs1 units
# weighted least squares via firls on dense band list
bands, des = [], []
for a, b in zip(grid_p[:-1], grid_p[1:]):
    bands += [a, b]; des += [1 / cic_resp(a), 1 / cic_resp(b)]
bands += [fs_, 0.5]; des += [0, 0]
w = [1] * (len(grid_p) - 1) + [40]
h_cf = signal.firls(NCF, np.array(bands) * 2, des, weight=w)
h_cf /= h_cf.sum() * cic_resp(0)  # DC gain 1
cf_rx = quant(h_cf, 17)            # Q1.17, DC gain 1
cf_tx = quant(2 * h_cf, 16)        # Q2.16, DC gain 2 (interp x2)

# ---------------- RRC at 4 sps ---------------------------------------------------
SPAN = 10
h_r = rrc(4, SPAN, ALPHA)
NRRC = len(h_r)
rrc_rx = quant(h_r / h_r.sum(), 17)          # DC gain 1
rrc_tx = quant(4 * h_r / h_r.sum(), 16)      # DC gain 4 (interp x4)

# ---------------- Preamble: 64 x +-1, 4 non-coherent quarters ---------------------
rng = np.random.default_rng(12345)


def det_metric(p, x):
    """sliding metric sum_q |sum_{k in q} p_k x_{n-63+k}|^2 over full x"""
    L = len(p)
    out = []
    for n in range(L - 1, len(x)):
        w = x[n - L + 1:n + 1]
        m = 0
        for q in range(4):
            m += abs(np.dot(p[16 * q:16 * q + 16], w[16 * q:16 * q + 16])) ** 2
        out.append(m)
    return np.array(out)


best, bestp = 1e9, None
for it in range(3000):
    p = rng.choice([-1, 1], 64)
    xs = np.concatenate([np.zeros(63), p, np.zeros(63)])
    m = det_metric(p, xs)
    pk = m.argmax()
    side = np.delete(m, pk).max()
    if side < best:
        best, bestp = side, p
peak = 4 * 16 ** 2
print(f"preamble: peak={peak}, max sidelobe={best:.0f}  ({10*np.log10(peak/best):.1f} dB)")
pre_bits = ''.join('1' if b > 0 else '0' for b in bestp)  # p[0] first transmitted
pre_hex = int(pre_bits[::-1], 2)   # bit k = p[k]

# ---------------- CORDIC atan table (2^32 = 2*pi) -------------------------------------
NIT = 20
atan_tab = [int(round(np.arctan(2.0 ** -i) / (2 * np.pi) * 2 ** 32)) for i in range(NIT)]
K = np.prod([1 / np.sqrt(1 + 2.0 ** (-2 * i)) for i in range(NIT)])

# ---------------- Emit -----------------------------------------------------------------
with open(OUT, "w") as fo:
    fo.write("// AUTO-GENERATED by scripts/gen_coefs.py -- do not edit\n")
    fo.write("package nb_coefs_pkg;\n")
    fo.write(f"  localparam int CF_NTAP  = {NCF};\n")
    fo.write(f"  localparam int RRC_NTAP = {NRRC};\n")
    fo.write(f"  localparam logic [{NCF*CW-1}:0] CF_RX_COEF  = {packvec(cf_rx)};  // Q1.17, DC=1\n")
    fo.write(f"  localparam logic [{NCF*CW-1}:0] CF_TX_COEF  = {packvec(cf_tx)};  // Q2.16, DC=2\n")
    fo.write(f"  localparam logic [{NRRC*CW-1}:0] RRC_RX_COEF = {packvec(rrc_rx)}; // Q1.17, DC=1\n")
    fo.write(f"  localparam logic [{NRRC*CW-1}:0] RRC_TX_COEF = {packvec(rrc_tx)}; // Q2.16, DC=4\n")
    fo.write(f"  localparam logic [63:0] PREAMBLE = 64'h{pre_hex:016x}; // bit k = symbol k (1:+S(1+j), 0:-S(1+j))\n")
    fo.write(f"  localparam int CORDIC_NIT = {NIT};\n")
    fo.write(f"  localparam logic [{NIT*32-1}:0] CORDIC_ATAN = {{" +
             ", ".join(f"32'd{a}" for a in reversed(atan_tab)) + "};\n")
    fo.write(f"  localparam int CORDIC_INVK_Q17 = {int(round(K * 2**17))}; // 1/K = {K:.6f}\n")
    fo.write("endpackage\n")

np.savez(os.path.join(os.path.dirname(__file__), "coefs.npz"), cf=h_cf, rrc=h_r, pre=bestp,
         cf_rx=cf_rx, cf_tx=cf_tx, rrc_rx=rrc_rx, rrc_tx=rrc_tx)

# ---------------- Report ---------------------------------------------------------------
w_, H = signal.freqz(h_cf, worN=4096, fs=1.0)
Hc = np.abs(H) * cic_resp(w_)
pb = w_ <= 0.078
sb = w_ >= 0.42
print(f"CFIR: {NCF} taps, passband ripple (CIC*CFIR) {20*np.log10(Hc[pb].max()/Hc[pb].min()):.3f} dB, "
      f"stopband {20*np.log10(np.abs(H[sb]).max()):.1f} dB")
w2, H2 = signal.freqz(h_r / h_r.sum(), worN=4096, fs=4.0)  # in Rs units
print(f"RRC: {NRRC} taps, stop (>0.75Rs) {20*np.log10(np.abs(H2[w2>0.75]).max()):.1f} dB")
rc = np.convolve(h_r, h_r); rc /= rc.max()
isi = np.delete(rc[len(rc)//2 % 4::4], len(rc)//2 // 4)
print(f"RC (TX*RX) ISI rms {20*np.log10(np.sqrt((isi**2).sum())):.1f} dB")
print("wrote", os.path.abspath(OUT))
